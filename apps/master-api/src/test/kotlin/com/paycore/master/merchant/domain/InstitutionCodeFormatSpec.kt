package com.paycore.master.merchant.domain

import io.kotest.assertions.throwables.shouldThrow
import io.kotest.assertions.withClue
import io.kotest.core.spec.style.BehaviorSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldNotContain
import org.springframework.core.io.ClassPathResource
import tools.jackson.databind.json.JsonMapper

/**
 * 기관 식별 코드 공통 형식(INST-CODE-001, D-INST-CODE-001): 매입사 코드([AcquirerCode])·Route 코드([RouteRef])는 `^[A-Z0-9]{1,32}$`만 생성된다(IC-1).
 * 하이픈·밑줄·소문자·공백·전각·빈 값·33자는 거절하고 메시지에 입력 원문을 넣지 않는다. 종단 대조(IC-3): Simulator 인증 결과 golden(harness 독립 생성 —
 * `contracts/authentication-contract-v1.golden.json`, VC-CREDIT-OK)의 매입사 코드를 MASTER 카드사 개통 매입사로 그대로 만들 수 있다.
 */
class InstitutionCodeFormatSpec : BehaviorSpec({

    val rejected = listOf("SIMACQ-A", "SIM_ACQ_A", "SIM-VAN-01", "SIM_VAN_01", "simacqa", "SimAcqA", "", " SIMACQA", "SIMACQA ", "SIM ACQ", "SIMVAN.01", "SIM:VAN", "A".repeat(33), "ＳIMACQA")

    Given("the common institution code format ^[A-Z0-9]{1,32}$") {
        Then("upper-case letters and digits of 1..32 characters are accepted as acquirer and route codes") {
            listOf("SIMACQA", "SIMVAN01", "A", "9", "A".repeat(32), "SIMCARD01").forEach { code ->
                AcquirerCode(code).value shouldBe code
                RouteRef(code).value shouldBe code
            }
        }

        Then("a hyphen, an underscore, lower case, spaces, other punctuation, full-width letters, empty and 33 characters are rejected without echoing the input") {
            rejected.forEach { code ->
                withClue("acquirer [$code]") {
                    val error = shouldThrow<IllegalArgumentException> { AcquirerCode(code) }
                    if (code.isNotBlank()) error.message!! shouldNotContain code
                }
                withClue("route [$code]") {
                    val error = shouldThrow<IllegalArgumentException> { RouteRef(code) }
                    if (code.isNotBlank()) error.message!! shouldNotContain code
                }
            }
        }
    }

    Given("the Simulator authentication result contract (golden generated by the harness, independent of the apps)") {
        val golden = JsonMapper.builder().build().readTree(ClassPathResource("contracts/authentication-contract-v1.golden.json").inputStream)
        val authenticated = golden.get("scenarios").get("authenticated")

        Then("the acquirer of the VC-CREDIT-OK result becomes the MASTER card route acquirer unchanged (MASTER acquirer = Simulator acquirer)") {
            authenticated.get("card").stringValue() shouldBe "VC-CREDIT-OK"
            val simulatorAcquirer = authenticated.get("lookup").get("acquirerCode").stringValue()
            AcquirerCode(simulatorAcquirer).value shouldBe simulatorAcquirer
        }

        Then("the malformed hyphen and underscore vectors of the same contract are not MASTER acquirer codes either") {
            listOf("hyphenatedAcquirerCode" to "acquirerCode", "underscoreIssuerCode" to "issuerCode", "hyphenatedProviderCode" to "providerCode").forEach { (vector, field) ->
                val code = golden.get("malformedLookups").get(vector).get(field).stringValue()
                withClue(vector) { shouldThrow<IllegalArgumentException> { AcquirerCode(code) } }
            }
        }
    }
})
